def fmt_num(v):
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}"
    if isinstance(v, float):
        return f"{round(v, 9):g}"
    return str(v)


def tm_text(c):
    try:
        return (f"{fmt_num(c['mv_conc'])} mM Na⁺, {fmt_num(c['dv_conc'])} mM Mg²⁺, "
                f"{fmt_num(c['dntp_conc'])} mM dNTP, {fmt_num(c['dna_conc'])} nM primer")
    except (KeyError, TypeError):
        return None


def _span_text(v):
    return f"{fmt_num(v[0])}–{fmt_num(v[1])}" if isinstance(v, (list, tuple)) and len(v) == 2 else None


def param_row(key, value, run_type=None):
    """(group, row) for one sealed parameter. row: key, label, text, tip, kind, value. Nested values keep their JSON in
    row['raw'] and are shown behind a disclosure."""
    group, label, unit, kind = PARAM_DISPLAY.get(key, (None, key, "", None))
    if group is None:
        group = INTERNALS if key.startswith(("structural_", "classify_")) else OTHER
    if run_type in ("in-silico-pcr", "genome-scan") and key in _SEARCH_KEYS:
        group, label = G_PCR, _SEARCH_KEYS[key]
        unit = "bp"
    tip = f"manifest key: {key}"
    raw = None
    if isinstance(value, (dict, list)) and not (kind in ("span", "tm", "target") or
                                                (isinstance(value, list) and all(not isinstance(x, (dict, list)) for x in value))):
        text, raw = "see raw sealed parameters", json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True)
    elif value is None:
        text = {"target": "none (untargeted design)", "region": "the whole record"}.get(kind, "none")
    elif kind == "fraction":
        text, tip = f"{fmt_num(round(value * 100, 6))} %", tip + f" · sealed value {fmt_num(value)}"
    elif kind == "pct":
        text = f"{fmt_num(value)} %"
    elif kind == "coord":
        text = COORD_TEXT if value == "0-based-half-open" else str(value)
    elif kind == "tm":
        text = tm_text(value) or json.dumps(value, sort_keys=True)
    elif kind == "target" and isinstance(value, (list, tuple)) and len(value) == 2:
        text = f"start {fmt_num(value[0])}, length {fmt_num(value[1])} nt (0-based)"
    elif kind in ("span", "region") and _span_text(value):
        text = _span_text((value[0], value[0] + value[1]) if kind == "region" else value) + " (0-based, half-open)"
    elif isinstance(value, list):
        text = ", ".join(fmt_num(x) for x in value)
    else:
        text = fmt_num(value)
        if unit and kind not in ("seq", "hash") and not isinstance(value, str):
            text += f" {unit}"
    return group, {"key": key, "label": label, "text": text, "tip": tip, "kind": kind, "raw": raw,
                   "value": value if kind in ("hash", "seq") else None}


def param_sections(manifest):
    """[(group, [rows])] in reading order from the manifest's sealed parameters. Every key appears exactly once."""
    run_type = (manifest or {}).get("runType")
    out = {}
    for key, value in ((manifest or {}).get("parameters") or {}).items():
        group, row = param_row(key, value, run_type)
        out.setdefault(group, []).append(row)
    return [(g, out[g]) for g in GROUP_ORDER if g in out] + [(g, r) for g, r in out.items() if g not in GROUP_ORDER]


def group_hash(h):
    h = str(h or "")
    return " ".join(h[i:i + 8] for i in range(0, len(h), 8))


def short_hash(h, n=12):
    return str(h or "")[:n]


def source_line(inp):
    """'NCBI nuccore AF123 · retrieved 2026-01-01T…Z', or None for a pasted sequence."""
    inp = inp or {}
    if inp.get("inputType") not in ("fetched_accession", "fetched_coordinate"):
        return None
    label = SOURCE_LABEL.get(inp.get("source"), str(inp.get("source") or "public database"))
    regions = inp.get("regions") or []
    where = ", ".join(f"{r.get('chrAccession')}:{r.get('start')}-{r.get('end')}" +
                      (" (reverse strand)" if r.get("strand") == 2 else "") for r in regions) or inp.get("accession")
    return f"{label} {where} · retrieved {inp.get('retrievedUtc') or 'time not recorded'}"


@functools.lru_cache(maxsize=4)
def _bundled_panel(path, mtime):
    with open(path, "rb") as fh:
        data = fh.read()
    names = re.findall(rb"^NAME\s+(\S+)\s*\n(?:.*\n)*?ACC\s+(\S+)", data, re.M)
    return hashlib.sha256(data).hexdigest(), [(a.decode(), b.decode()) for a, b in names]


def panel_profiles(manifest):
    """(profiles, note) for the Pfam panel a run sealed. The bundled file is re-hashed and must equal the sealed
    SHA-256 before its accession list is shown; otherwise the list is withheld and the note says why.
    profiles: [{code, name, accession, label}]"""
    from teagle_core import domains
    sealed = next((d.get("sha256") for d in (manifest or {}).get("databases") or []
                   if "pfam" in str(d.get("name", "")).lower() and d.get("sha256")), None)
    if not sealed:
        return [], None
    path = getattr(domains, "HMM_PATH", None)
    try:
        digest, entries = _bundled_panel(path, os.path.getmtime(path))
    except (OSError, TypeError):
        return [], "The bundled profile file could not be read, so its accession list is not shown."
    if digest != sealed:
        return [], ("The bundled profile file differs from the one this run sealed, so its accession list is not shown.")
    out = []
    for name, acc in entries:
        code, label = (domains.DOMAIN_INFO.get(name) or (name, name))[:2]
        out.append({"code": code, "name": name, "accession": acc, "label": label})
    return out, None


def input_rows(manifest):
    inp = (manifest or {}).get("input") or {}
    rows = [("Record", inp.get("id") or "—", None),
            ("Identity", IDENTITY_LABEL.get(inp.get("identitySource"), inp.get("identitySource") or "—"), None),
            ("Length", f"{inp['length']:,} bp" if isinstance(inp.get("length"), int) else "—", None),
            ("Sequence SHA-256", inp.get("sha256") or "—", "hash" if inp.get("sha256") else None)]
    src = source_line(inp)
    rows.append(("Source", src or "pasted or uploaded sequence", None))
    if len(inp.get("records") or []) > 1:
        rows.append(("Records", f"{len(inp['records'])}", None))
    return rows


