def svg_image(svg, scale=3, paper="#ffffff"):
    """Rasterise an SVG string onto an opaque page-coloured QImage."""
    from PySide6.QtCore import QByteArray
    from PySide6.QtGui import QColor, QImage, QPainter
    from PySide6.QtSvg import QSvgRenderer
    m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
    w, h = (float(m.group(1)), float(m.group(2))) if m else (800.0, 400.0)
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    img = QImage(int(w * scale), int(h * scale), QImage.Format_ARGB32)
    img.fill(QColor(paper))
    painter = QPainter(img)
    renderer.render(painter)
    painter.end()
    return img


def write_document_pdf(html_text, images, path):
    """Print a rich-text document to an A4 PDF with 15 mm margins. `images` maps a resource name used in the HTML to a
    QImage. The PDF carries no author or creator metadata."""
    from PySide6.QtCore import QMarginsF, QSizeF, QUrl
    from PySide6.QtGui import QFont, QPageLayout, QPageSize, QPdfWriter, QTextDocument

    def write(tmp):
        writer = QPdfWriter(tmp)
        writer.setCreator("")
        writer.setTitle("")
        writer.setResolution(96)
        writer.setPageSize(QPageSize(QPageSize.A4))
        writer.setPageMargins(QMarginsF(15, 15, 15, 15), QPageLayout.Unit.Millimeter)
        doc = QTextDocument()
        doc.setDefaultFont(QFont("Times New Roman", 10))
        doc.setPageSize(QSizeF(writer.pageLayout().paintRectPixels(96).size()))
        for name, img in (images or {}).items():
            doc.addResource(QTextDocument.ImageResource, QUrl(name), img)
        doc.setHtml(html_text)
        doc.print_(writer)
        del writer
        from teagle_core.artifact_metadata import clean_pdf_metadata
        clean_pdf_metadata(tmp, author=None)

    import widgets
    widgets.atomic_save(path, write)
