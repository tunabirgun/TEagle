def report_html(ctx, figures=None, qt=False):
    """Self-contained page: no script, no external resource, no comment. `figures` maps 'map' and 'gel' to an HTML snippet
    (inline <svg> for the file, an <img> resource name for the PDF); a missing figure is simply not drawn."""
    figures = figures or {}
    e = html.escape
    body = [f"<h1>Assay record</h1>", f"<p>{e(_header(ctx))}</p>"]
    for heading, lines in sections(ctx, with_map=bool(figures.get("map"))):
        body.append(f"<h2>{e(heading)}</h2>")
        bullets = []
        for ln in lines:
            if ln.startswith("• "):
                bullets.append(f"<li>{e(ln[2:])}</li>")
                continue
            if bullets:
                body.append("<ul>" + "".join(bullets) + "</ul>"); bullets = []
            body.append(f"<p>{e(ln)}</p>")
        if bullets:
            body.append("<ul>" + "".join(bullets) + "</ul>")
        if heading == "Element map" and figures.get("map"):
            body.append(f"<p>{figures['map']}</p>")
        if heading == "In-silico PCR" and figures.get("gel"):
            body.append(f"<p>Predicted gel (from the sequence; not a measured gel):</p><p>{figures['gel']}</p>")
    return ("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            f"<title>Assay record</title><style>{_CSS_QT if qt else _CSS}</style></head><body>" + "".join(body) + "</body></html>")


def with_footer(svg, lines, ink="#444444", px=7.5):
    """The figure with identifying lines under it (the view box and height grow to hold them); unchanged when there are
    no lines or no readable view box. Meant for exported figures only."""
    import textwrap
    lines = [ln for ln in lines or [] if ln]
    m = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg)
    if not lines or not m:
        return svg
    w, h = float(m.group(1)), float(m.group(2))
    wrapped = [part for ln in lines for part in textwrap.wrap(ln, max(24, int((w - 16) / (px * 0.62))))]
    grow = 6 + 11 * len(wrapped)
    text = "".join(f'<text x="8" y="{h + 6 + 11 * (i + 1) - 3:g}" font-size="{px:g}" fill="{ink}">{html.escape(t)}</text>'
                   for i, t in enumerate(wrapped))
    out = svg.replace(m.group(0), f'viewBox="0 0 {w:g} {h + grow:g}"', 1)
    out = re.sub(r'(<svg\b[^>]*?\sheight=")[\d.]+(")', lambda k: f"{k.group(1)}{h + grow:g}{k.group(2)}", out, count=1)
    return out.replace("</svg>", text + "</svg>")


