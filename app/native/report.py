def feature_spans(rec):
    """[(label, start, end)] of every called feature on the record, 0-based half-open."""
    out = []
    for e in rec.get("structural") or []:
        if e.get("advisory") or "advisory" in str(e.get("type", "")):
            continue
        name = str(e.get("type", "feature")).split(" (")[0]
        for key, tag in (("five_prime", " (5′ copy)"), ("three_prime", " (3′ copy)"),
                         ("upstream", " (upstream)"), ("downstream", " (downstream)")):
            if isinstance(e.get(key), (list, tuple)) and len(e[key]) == 2:
                out.append((name + tag, e[key][0], e[key][1]))
        if isinstance(e.get("pos"), (list, tuple)) and len(e["pos"]) == 2:
            out.append((name, e["pos"][0], e["pos"][1]))
    for d in rec.get("domains") or []:
        out.append((f"{d['domain']} ({d.get('hmm') or d['domain']})", d["nt"][0], d["nt"][1]))
    return out


def overlaps(span, features):
    if not span:
        return []
    return list(dict.fromkeys(label for label, s, e in features if s < span[1] and span[0] < e))


