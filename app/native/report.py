_TESORTER_SUPERFAMILY = {"Tc1–Mariner": "Tc1_Mariner", "CACTA": "EnSpm_CACTA", "Mutator": "MuDR_Mutator"}
_LTR_FULL = {"GAG", "PR", "INT", "RT", "RNaseH"}


def _cell(v):
    return re.sub(r"[\t\r\n]+", " ", str(v)).strip()


def _scan_status(rec, cl):
    from teagle_core import gff3
    if not cl or ((rec.get("processing") or {}).get("domains") or {}).get("status") == "not_run":
        return "not_run"
    return gff3.domain_scan_state(cl)[0]


def _domain_strand_and_tokens(rec, status):
    ds = rec.get("domains") or []
    if status == "unavailable_failed":
        return "NA", "unavailable"
    if status == "not_run":
        return "NA", "not_run"
    if not ds:
        return "NA", "none"
    strands = {d.get("strand") for d in ds}
    strand = strands.pop() if len(strands) == 1 and next(iter(strands), None) in ("+", "-") else "?"
    ordered = sorted(ds, key=lambda d: d["nt"][0], reverse=(strand == "-"))
    return strand, " ".join(f"{d['domain']}|{d.get('hmm') or d['domain']}" for d in ordered)


def cls_row(rec, rank_view, call_view):
    """One row of the classification table. `rank_view` and `call_view` are the application's own display mappings, so
    this file and the screen read the same Wicker code and the same call status."""
    seq = rec.get("seq") or ""
    length = (rec.get("composition") or {}).get("length") or len(seq)
    digest = hashlib.sha256(seq.encode("utf-8")).hexdigest()
    cl = rec.get("classification") or {}
    status = call_view(rec)["status"]
    def dead(outcome):
        return [rec.get("id", "NA")] + ["NA"] * 9 + [outcome] + ["NA"] * 3 + [length, digest]
    if not rec.get("valid", True):
        return dead("invalid_input")
    if status == "failed" or not cl:
        return dead("failed" if status == "failed" else "not_run")
    te, outcome = str(cl.get("te_class") or "NA"), cl.get("outcome") or "complete"
    view = None if outcome == "withheld" else rank_view(cl)
    if te == "none":
        order = family = wicker = rm = "NA"
    elif view is None:
        order, family, wicker, rm = "unknown", "unknown", "XXX", "Unknown"
    else:
        order = view["order"] or "unknown"
        family = _TESORTER_SUPERFAMILY.get(view["superfamily"], view["superfamily"]) or "unknown"
        wicker, rm = view["code"], view["rm"] or "Unknown"
    present = set((cl.get("completeness") or {}).get("present") or [])
    complete = ("NA" if te == "none" else
                ("yes" if outcome == "complete" and _LTR_FULL <= present else "no") if family in ("Copia", "Gypsy")
                else "unknown")
    scan = _scan_status(rec, cl)
    strand, tokens = _domain_strand_and_tokens(rec, scan)
    return [rec.get("id", "NA"), order, family, "NA", complete, strand, tokens, rm, wicker, te, outcome,
            call_view(rec)["confidence"] or "NA", (cl.get("completeness") or {}).get("tier") or "NA", scan, length, digest]


def classification_tsv(records, rank_view, call_view):
    rows = [CLS_TSV_HEADER] + [cls_row(r, rank_view, call_view) for r in records]
    return "\n".join("\t".join(_cell(c) for c in row) for row in rows) + "\n"


