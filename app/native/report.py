def plain(x):
    return "—" if x is None else f"{x:g}" if isinstance(x, (int, float)) else str(x)


def _pair_line(p):
    def side(tag, seq, span):
        return f"{tag} 5′-{seq}-3′" + (f" ({span[0]}–{span[1]})" if span else "")
    bits = [p["label"], side("F", p["fwd"], p.get("fwd_span")), side("R", p["rev"], p.get("rev_span"))]
    if p.get("product") is not None:
        bits.append(f"product {p['product']:,} bp")
    if p.get("amplicon_span"):
        bits.append(f"amplicon {p['amplicon_span'][0]}–{p['amplicon_span'][1]}")
        bits.append("spans " + (", ".join(p.get("spans") or []) or "no called feature"))
    if p.get("tm"):
        bits.append(f"Tm {plain(p['tm'][0])}/{plain(p['tm'][1])} °C")
    if p.get("gc"):
        bits.append(f"GC {plain(p['gc'][0])}/{plain(p['gc'][1])} %")
    bits.append("structure QC " + (p.get("qc") or "n/a"))
    if p.get("note"):
        bits.append(p["note"])
    return " · ".join(bits)


def sections(ctx, with_map=False):
    """[(heading, [line, ...])] shared by the notebook text and the report. A line starting '• ' is a bullet. The element
    map is a figure, so its heading appears only in the report."""
    sp, call = ctx.get("specimen") or {}, ctx.get("call") or {}
    out = []
    pos = f" (record {sp['position'][0]} of {sp['position'][1]})" if sp.get("position") else ""
    lines = [f"Record {sp.get('id', '—')}{pos} · {sp.get('length', 0):,} bp"
             + (f" · GC {plain(sp['gc'])} %" if sp.get("gc") is not None else "")
             + f" · Sequence SHA-256 {sp.get('sha256', '—')}", sp.get("source") or "Source: pasted or uploaded sequence"]
    out.append(("Specimen", lines))
    cl = [call.get("headline") or "—"]
    cl[0] += (f" — {call['superfamily']}" if call.get("superfamily") else "")
    cl[0] += f" · confidence {call['confidence']}" if call.get("confidence") else ""
    if call.get("chip"):
        cl[0] += f" · {call['chip']}"
    for key, lead in (("rank_line", ""), ("why", "Why: "), ("completeness", "Completeness: "), ("coding", "Coding structure: ")):
        if call.get(key):
            cl.append(lead + call[key])
    cl.append("Cautions:")
    cl += ["• " + c for c in call.get("cautions") or []] + ["• " + CAVEAT]
    out.append(("Call", cl))
    if with_map:
        out.append(("Element map", []))
    pairs = ctx.get("pairs") or []
    pl = [_pair_line(p) for p in pairs] or ["No primer pair has been designed on this record."]
    if ctx.get("pairs_note"):
        pl.append(ctx["pairs_note"])
    if ctx.get("excluded"):
        pl.append(f"Primer pairs designed on another record are not included ({ctx['excluded']}).")
    out.append(("Primer pairs", pl))
    pcr = ctx.get("pcr") or {}
    out.append(("In-silico PCR", pcr.get("lines") or ["In-silico PCR has not been run for these pairs."]))
    if ctx.get("scan"):
        out.append(("Genome scan", ctx["scan"]))
    out.append(("Conditions", ctx.get("conditions") or ["No primer design on this record, so no design conditions are recorded."]))
    pv = ctx.get("provenance") or {}
    pl = [f"{label} seal {seal}" for label, seal in pv.get("runs") or []]
    if pv.get("software"):
        pl.append("Software: " + pv["software"])
    if pv.get("panel"):
        pl.append(pv["panel"])
    pl.append("Full manifests: panel 07 → Export all runs (.json)")
    out.append(("Provenance", pl))
    return out


