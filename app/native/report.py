def run_title(n, manifest, extra=""):
    m = manifest or {}
    inp = m.get("input") or {}
    created = str(m.get("createdUtc") or "")
    clock = created[11:19] + " UTC" if len(created) >= 19 else "time not recorded"
    return f"{n} · {RUN_LABEL.get(m.get('runType'), m.get('runType') or 'run')} · {inp.get('id') or '—'} · {clock}{extra}"


