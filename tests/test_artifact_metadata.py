def test_media_gate_observably_rejects_then_cleans_generator_metadata(tmp_path):
    from PIL import Image, PngImagePlugin
    from pypdf import PdfReader, PdfWriter
    from pypdf.generic import DecodedStreamObject, NameObject

    svg = tmp_path / "dirty.svg"
    svg.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg"><metadata><creator>Matplotlib</creator></metadata></svg>',
        encoding="utf-8",
    )
    png = tmp_path / "dirty.png"
    png_meta = PngImagePlugin.PngInfo()
    png_meta.add_text("Software", "Matplotlib")
    Image.new("RGB", (2, 2), "white").save(png, pnginfo=png_meta)
    pdf = tmp_path / "dirty.pdf"
    writer = PdfWriter()
    writer.add_blank_page(width=10, height=10)
    writer.add_blank_page(width=10, height=10)
    writer.add_outline_item("First page", 0)
    writer.page_mode = "/UseOutlines"
    writer.open_destination = writer.pages[0]
    writer.add_metadata({"/Producer": "generator", "/CreationDate": "D:20260813", "/Trapped": "/False"})
    xmp = DecodedStreamObject()
    xmp.set_data(
        b'<?xpacket begin="x"?>'
        b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><dirty>DIRTY-XMP</dirty></x:xmpmeta>'
        b'<?xpacket end="w"?>'
    )
    xmp.update({NameObject("/Type"): NameObject("/Metadata"), NameObject("/Subtype"): NameObject("/XML")})
    writer.root_object[NameObject("/Metadata")] = writer._add_object(xmp)
    writer.generate_file_identifiers()
    with pdf.open("wb") as stream:
        writer.write(stream)

    for path in (svg, png, pdf):
        assert media_metadata_violations(path), path

    clean_svg_metadata(svg)
    clean_png_metadata(png)
    clean_pdf_metadata(pdf)
    for path in (svg, png, pdf):
        assert media_metadata_violations(path) == [], path
    cleaned_pdf = PdfReader(pdf)
    assert len(cleaned_pdf.outline) == 1
    assert cleaned_pdf.page_mode == "/UseOutlines"
    assert "/OpenAction" in cleaned_pdf.root_object
    raw_pdf = pdf.read_bytes()
    assert b"DIRTY-XMP" not in raw_pdf
    assert b"/Metadata" not in raw_pdf
    assert b"/Trapped" not in raw_pdf


@pytest.mark.parametrize(
    "feature", ["encrypted", "acroform", "attachment", "perms", "signature", "docmdp", "incremental"],
)
def test_pdf_unsafe_features_refuse_and_preserve_destination(tmp_path, feature):
    from pypdf import PdfWriter
    from pypdf.generic import ArrayObject, DictionaryObject, NameObject, NumberObject

    path = tmp_path / f"{feature}.pdf"
    writer = PdfWriter()
    writer.add_blank_page(width=10, height=10)
    if feature == "encrypted":
        writer.encrypt("secret")
    elif feature == "acroform":
        writer.root_object[NameObject("/AcroForm")] = DictionaryObject()
    elif feature == "attachment":
        writer.add_attachment("evidence.txt", b"embedded")
    elif feature == "perms":
        writer.root_object[NameObject("/Perms")] = DictionaryObject()
    elif feature == "signature":
        signature = DictionaryObject({
            NameObject("/Type"): NameObject("/Sig"),
            NameObject("/ByteRange"): ArrayObject([NumberObject(0), NumberObject(1)]),
        })
        writer.root_object[NameObject("/SignatureProbe")] = writer._add_object(signature)
    elif feature == "docmdp":
        transform = DictionaryObject({NameObject("/TransformMethod"): NameObject("/DocMDP")})
        writer.root_object[NameObject("/TransformProbe")] = writer._add_object(transform)
    with path.open("wb") as stream:
        writer.write(stream)
    if feature == "incremental":
        path.write_bytes(path.read_bytes() + b"\n%%EOF\n")
    original = path.read_bytes()
    assert media_metadata_violations(path)
    with pytest.raises(ValueError, match="PDF|encrypted"):
        clean_pdf_metadata(path)
    assert path.read_bytes() == original


