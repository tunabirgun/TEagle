@pytest.mark.parametrize("mutation", ["invalid_idat", "invalid_ihdr"])
def test_png_crc_valid_decode_or_ihdr_mutation_refuses_and_preserves_destination(tmp_path, mutation):
    from PIL import Image
    from teagle_core import artifact_metadata

    path = tmp_path / "mutated.png"
    Image.new("RGB", (2, 2), "white").save(path)
    chunks = artifact_metadata._png_chunks(path.read_bytes())
    mutated = bytearray(artifact_metadata._PNG_SIGNATURE)
    changed = False
    for chunk_type, payload in chunks:
        if mutation == "invalid_idat" and chunk_type == b"IDAT" and not changed:
            payload = zlib.compress(b"not valid scanlines")
            changed = True
        elif mutation == "invalid_ihdr" and chunk_type == b"IHDR":
            payload = struct.pack(">II", 0, 2) + payload[8:]
            changed = True
        mutated.extend(artifact_metadata._png_chunk(chunk_type, payload))
    assert changed
    path.write_bytes(bytes(mutated))
    original = path.read_bytes()
    assert media_metadata_violations(path)
    with pytest.raises(ValueError):
        clean_png_metadata(path)
    assert path.read_bytes() == original


