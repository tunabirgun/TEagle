def _dirty_ooxml(path: Path) -> None:
    with ZipFile(path, "w", compression=ZIP_DEFLATED) as package:
        package.writestr(
            "[Content_Types].xml",
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Override PartName="/docProps/core.xml" ContentType="core"/>'
            '<Override PartName="/docProps/app.xml" ContentType="app"/>'
            '</Types>',
        )
        package.writestr(
            "_rels/.rels",
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" Type="core" Target="docProps/core.xml"/>'
            '<Relationship Id="rId2" Type="app" Target="docProps/app.xml"/>'
            '</Relationships>',
        )
        package.writestr(
            "docProps/core.xml",
            '<cp:coreProperties xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:creator>python-docx</dc:creator>'
            '<dc:description>generated by python-docx</dc:description></cp:coreProperties>',
        )
        package.writestr("docProps/app.xml", "<Properties><Application>openpyxl</Application></Properties>")
        package.writestr(
            "word/document.xml",
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" '
            'xmlns:w14="http://schemas.microsoft.com/office/word/2010/wordml">'
            '<w:p w:rsidR="12345678" w14:paraId="AABBCCDD"><w:r><w:t>x</w:t></w:r></w:p>'
            '</w:document>',
        )


