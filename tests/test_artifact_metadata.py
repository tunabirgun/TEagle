def test_ooxml_cleaner_is_atomic_when_validation_or_replace_fails(tmp_path, monkeypatch):
    from teagle_core import artifact_metadata

    path = tmp_path / "atomic.docx"
    _dirty_ooxml(path)
    original = path.read_bytes()

    monkeypatch.setattr(
        artifact_metadata,
        "ooxml_metadata_violations",
        lambda _path, **_kw: ["injected validation failure"],
    )
    with pytest.raises(ValueError, match="injected validation failure"):
        clean_ooxml_metadata(path)
    assert path.read_bytes() == original
    assert not list(tmp_path.glob("*.tmp"))

    monkeypatch.setattr(
        artifact_metadata,
        "ooxml_metadata_violations",
        ooxml_metadata_violations,
    )
    monkeypatch.setattr(
        artifact_metadata,
        "_replace_file",
        lambda _source, _target: (_ for _ in ()).throw(OSError("injected replace failure")),
    )
    with pytest.raises(OSError, match="injected replace failure"):
        clean_ooxml_metadata(path)
    assert path.read_bytes() == original
    assert not list(tmp_path.glob("*.tmp"))


