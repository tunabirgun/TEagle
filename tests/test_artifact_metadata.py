def test_png_post_clean_decode_failure_preserves_destination(tmp_path, monkeypatch):
    from PIL import Image, PngImagePlugin
    from teagle_core import artifact_metadata

    path = tmp_path / "dirty.png"
    metadata = PngImagePlugin.PngInfo()
    metadata.add_text("Software", "optional")
    Image.new("RGB", (2, 2), "white").save(path, pnginfo=metadata)
    original = path.read_bytes()
    real_decode = artifact_metadata._strict_png_decode
    calls = 0

    def reject_candidate(payload, chunks):
        nonlocal calls
        calls += 1
        if calls == 2:
            raise ValueError("injected PNG post-clean decode failure")
        return real_decode(payload, chunks)

    monkeypatch.setattr(artifact_metadata, "_strict_png_decode", reject_candidate)
    with pytest.raises(ValueError, match="post-clean decode failure"):
        clean_png_metadata(path)
    assert path.read_bytes() == original


