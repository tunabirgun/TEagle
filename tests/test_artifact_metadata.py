def _ooxml_with_word_bibliography(
    path: Path,
    *,
    empty: bool = True,
    properties: str | None = None,
) -> None:
    bibliography = "http://schemas.openxmlformats.org/officeDocument/2006/bibliography"
    custom_xml = "http://schemas.openxmlformats.org/officeDocument/2006/customXml"
    source = (
        '<b:Sources xmlns:b="' + bibliography + '" xmlns="' + bibliography
        + '" SelectedStyle="/APA.XSL" StyleName="APA"'
    )
    if empty:
        source += '/>'
    else:
        source += '><b:Source><b:Tag>Required source</b:Tag></b:Source></b:Sources>'
    with ZipFile(path, "w", compression=ZIP_DEFLATED) as package:
        package.writestr(
            "[Content_Types].xml",
            '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Override PartName="/docProps/core.xml" '
            'ContentType="application/vnd.openxmlformats-package.core-properties+xml"/>'
            '<Override PartName="/customXml/itemProps1.xml" '
            'ContentType="application/vnd.openxmlformats-officedocument.customXmlProperties+xml"/>'
            '</Types>',
        )
        package.writestr(
            "_rels/.rels",
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" '
            'Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/core-properties" '
            'Target="docProps/core.xml"/>'
            '</Relationships>',
        )
        package.writestr(
            "docProps/core.xml",
            '<cp:coreProperties '
            'xmlns:cp="http://schemas.openxmlformats.org/package/2006/metadata/core-properties" '
            'xmlns:dc="http://purl.org/dc/elements/1.1/">'
            '<dc:creator>Tuna Birgun</dc:creator></cp:coreProperties>',
        )
        package.writestr(
            "word/document.xml",
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
            '<w:body><w:p><w:r><w:t>Visible document text</w:t></w:r></w:p></w:body></w:document>',
        )
        package.writestr(
            "word/_rels/document.xml.rels",
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/customXml" '
            'Target="../customXml/item1.xml"/>'
            '</Relationships>',
        )
        package.writestr("customXml/item1.xml", source)
        package.writestr(
            "customXml/_rels/item1.xml.rels",
            '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/customXmlProps" '
            'Target="itemProps1.xml"/>'
            '</Relationships>',
        )
        package.writestr(
            "customXml/itemProps1.xml",
            properties
            or (
                '<ds:datastoreItem xmlns:ds="' + custom_xml
                + '" ds:itemID="{EF278816-EC6F-A645-907D-7F25AECB1D4A}">'
                '<ds:schemaRefs><ds:schemaRef ds:uri="' + bibliography
                + '"/></ds:schemaRefs></ds:datastoreItem>'
            ),
        )


